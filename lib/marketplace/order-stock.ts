// "ออเดอร์ใบนี้ยังกินของในคลังเราอยู่ไหม" — เกณฑ์เดียวของทุก marketplace (client-safe)
//
// โมเดลสต็อกของระบบ:
//   คงคลัง (quantity) = ของที่ยังอยู่ในร้านจริง **รวมกล่องที่แพ็ครอขนส่งมารับ**
//   จอง (reserved)    = ส่วนที่ขายแล้วแต่ยังไม่ออกจากร้าน
//   ของหายจากคงคลังตอน **ออกจากร้าน** (ขนส่งรับไป) ไม่ใช่ตอนกดรับออเดอร์
//
// ⇒ เส้นแบ่งของการ "จองสต็อกให้ออเดอร์ที่เพิ่งดึงเข้ามา" ไม่ใช่ "ออเดอร์จบหรือยัง"
//   แต่คือ **"ของยังอยู่ในคลังไหม"** — ออเดอร์เก่าที่ขนส่งรับไปแล้ว/ยกเลิกแล้ว
//   ของไม่ได้อยู่ในร้านตั้งแต่ตอนพนักงานนับสต็อกครั้งล่าสุด จึงต้องไม่แตะคลังซ้ำ
//
// ⚠️ ที่ต้องมีเพราะ **สายสร้างออเดอร์ใหม่ของทุก platform เดิมจองสต็อกทุกใบไม่ดูสถานะ**
//    และไม่มีขาตัด/คืนตามมา (ตรรกะนั้นอยู่ในสาย "ออเดอร์ที่มีอยู่แล้วเปลี่ยนสถานะ")
//    ⇒ ดึงออเดอร์ย้อนหลังทีไร ออเดอร์ที่ส่ง/ยกเลิกไปแล้วกลายเป็น "ยอดจองค้างถาวร"
//    พร้อมขายหายเงียบ ๆ โดยไม่มีใครรู้ (เจอ 2026-09-16 · fix-bug.md)

/** สถานะภายในที่แปลว่า "ของยังอยู่ในคลังของเรา" — ที่เหลือคือออกไปแล้วหรือไม่เกิดการขาย */
export const STOCK_HOLDING_ORDER_STATUSES = ['new', 'ready_to_ship', 'processing'] as const;

/**
 * ออเดอร์สถานะนี้ยังกินของในคลังอยู่ไหม (= ต้องจองสต็อกให้)
 * รับ `order_status` **ภายในระบบ** ที่ map มาแล้ว ไม่ใช่สถานะดิบของแพลตฟอร์ม
 */
export function holdsStockInWarehouse(orderStatus: string): boolean {
  return (STOCK_HOLDING_ORDER_STATUSES as readonly string[]).includes(orderStatus);
}

/** เหตุผลที่ข้ามการจอง — ใช้เขียน log/ข้อความสรุปให้ผู้ใช้เห็นว่าอะไรถูกข้ามไป */
export function skipStockReason(orderStatus: string): string {
  return orderStatus === 'cancelled'
    ? 'ออเดอร์ถูกยกเลิกไปแล้ว'
    : 'ของออกจากคลังไปแล้ว (ขนส่งรับไปก่อนที่ระบบจะรู้จักออเดอร์นี้)';
}
