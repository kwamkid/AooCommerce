//
// ══════════════════════════════════════════════════════════════════════════
//  ทำไมต้องมี: "ดูดออเดอร์เข้ามา" กับ "รับออเดอร์ใหม่จริง" ไม่เหมือนกัน
// ══════════════════════════════════════════════════════════════════════════
//  ออเดอร์ใหม่ที่เพิ่งเข้า → ต้องจองสต็อก ออกเอกสาร แจ้งเตือน ครบทุกอย่าง
//  ออเดอร์ย้อนหลังที่ดึงมาเติมประวัติ → **ห้ามทำอะไรพวกนั้นเลย** เพราะของออกไปแล้ว
//  เอกสารก็ออกไปแล้ว การทำซ้ำจะทำให้สต็อกติดลบและเลขที่เอกสารเดินฟรี
//
//  ⚠️ เลขที่เอกสารคือตัวที่ย้อนกลับยากที่สุด — ยกเลิกได้แต่เลขไม่คืน
//
// ══════════════════════════════════════════════════════════════════════════
//  เกณฑ์ว่าออเดอร์ย้อนหลังควรตัดสต็อกมั้ย (ไว้ใช้ตอนทำ UI เต็มรูปแบบ)
// ══════════════════════════════════════════════════════════════════════════
//  **ไม่ใช่ "ออเดอร์จบหรือยัง" แต่คือ "ของออกจากชั้นก่อนหรือหลังวันที่นับสต็อก"**
//  เพราะตัวเลขสต็อกที่ตั้งไว้คือของที่นับได้ ณ วันนั้น ซึ่งหักของที่ส่งไปแล้วเรียบร้อย
//
//    ส่งแล้ว ก่อนวันนับ  → ห้ามตัด (ยอดที่นับหักไปแล้ว ตัดอีกจะติดลบ)
//    ส่งแล้ว หลังวันนับ  → ต้องตัด
//    ยังไม่ส่ง          → **จอง (reserve) ไม่ใช่ตัด** เพราะของยังอยู่บนชั้นจริง
//
//  ตอนที่ยังไม่เปิดใช้จริง ไม่ต้องคิดเรื่องนี้เลย — backfill แบบไม่แตะสต็อก
//  แล้วค่อยดึงสต็อกจากแพลตฟอร์มทับทีหลัง ตัวเลขจะถูกเองเพราะแพลตฟอร์มหักให้แล้ว

export interface OrderImportOptions {
  /** ไม่จอง/ไม่ตัดสต็อก */
  skipStock?: boolean;
  /** ไม่ออกเอกสารอัตโนมัติ (ABB/ใบเสร็จ) — เลขที่เอกสารย้อนกลับไม่ได้ */
  skipDocuments?: boolean;
  /** ไม่ส่งแจ้งเตือน "ออเดอร์ใหม่" */
  skipNotify?: boolean;
}

